const pad = (rows) => [...rows, ...Array(16).fill('................')].slice(0, 16);

const stack = (...layers) => pad(layers.flat());
const overlay = (base, top, offsetY) => {
  const rows = pad(base).map((row) => [...row]);
  top.forEach((row, y) => [...row].forEach((pixel, x) => {
    if (pixel === '#' && rows[y + offsetY]) rows[y + offsetY][x] = '#';
  }));
  return rows.map((row) => row.join(''));
};

