function bitmapFor(condition, isDay) {
  if (condition === 'clear' || condition === 'partly') return BITMAPS[`${condition}-${isDay ? 'day' : 'night'}`];
  return BITMAPS[condition] ?? BITMAPS.cloudy;
}

/** Draws a bitmap as one path, which keeps the SVG small and every pixel crisp. */
export function pixelIcon(condition, isDay, x, y, pixelSize, fill) {
  let d = '';
  bitmapFor(condition, isDay).forEach((row, py) => {
    [...row].forEach((pixel, px) => {
      if (pixel === '#') d += `M${x + px * pixelSize} ${y + py * pixelSize}h${pixelSize}v${pixelSize}h-${pixelSize}Z`;
    });
  });
  return `<path d="${d}" fill="${fill}"/>`;
}

